"""JSON Schemas for the pipeline's owner-to-owner boundaries (contract v1.1, rule 7).

Only a boundary that crosses between owners is exchanged as JSON (decision
BE-01); in-process boundaries stay pydantic objects.

- ``run_request.schema.json``       ``POST /runs`` body (Daniel -> backend)
- ``analysis.schema.json``          seed employees (``employees.json`` shape)
- ``personas_in.schema.json``       Part 1 answer (Robin -> CM ID)
- ``plot_outline.schema.json``      Plot -> Event content (Giulia -> Robin)
- ``event_content_in.schema.json``  Part 2 answer (Robin -> Valentin)
- ``document_plan.schema.json``     Document plan, whole run (Giulia -> Robin)
- ``case_document_plan.schema.json``  one case's plan (Giulia -> Robin)
- ``document_texts_in.schema.json`` Part 3 answer (Robin -> Valentin)
- ``trace_line.schema.json``        one trace line (every step -> Mike)
- ``run_result.schema.json``, ``error.schema.json``  ``POST /runs`` response

A schema carries the shape only. The rules between parts (no ``id``, closed
value sets, references) hold through the models and ``ingest_employees``, not
through the schema. Regenerate after every model change with:
``python3 -m pipeline.schema``
"""

import json
from pathlib import Path

from .contracts import (
    Analysis,
    CaseDocumentPlan,
    DocumentPlan,
    DocumentTextsIn,
    ErrorBody,
    EventContentIn,
    PersonasIn,
    PlotOutline,
    RunRequest,
    RunResult,
    TraceLine,
)

SCHEMA_DIR = Path(__file__).with_name("schema")

SCHEMAS = {
    "analysis.schema.json": lambda: Analysis.model_json_schema(by_alias=True),
    "run_request.schema.json": lambda: RunRequest.model_json_schema(by_alias=True),
    "personas_in.schema.json": lambda: PersonasIn.model_json_schema(by_alias=True),
    "plot_outline.schema.json": lambda: PlotOutline.model_json_schema(by_alias=True),
    "event_content_in.schema.json": lambda: EventContentIn.model_json_schema(by_alias=True),
    "document_plan.schema.json": lambda: DocumentPlan.model_json_schema(by_alias=True),
    "case_document_plan.schema.json": lambda: CaseDocumentPlan.model_json_schema(by_alias=True),
    "document_texts_in.schema.json": lambda: DocumentTextsIn.model_json_schema(by_alias=True),
    "trace_line.schema.json": lambda: TraceLine.model_json_schema(),
    "run_result.schema.json": lambda: RunResult.model_json_schema(mode="serialization"),
    "error.schema.json": lambda: ErrorBody.model_json_schema(),
}


def render(name):
    """The text of one schema file, exactly as it is committed."""
    schema = {"$schema": "https://json-schema.org/draft/2020-12/schema",
              "$comment": "Pipeline contract v1.1. Generated by python3 -m pipeline.schema; do not edit.",
              **SCHEMAS[name]()}
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def write_schemas():
    SCHEMA_DIR.mkdir(exist_ok=True)
    for name in SCHEMAS:
        (SCHEMA_DIR / name).write_text(render(name), encoding="utf-8")
    return SCHEMA_DIR


if __name__ == "__main__":
    print(f"wrote {', '.join(SCHEMAS)} to {write_schemas()}")
