"""JSON Schemas for the pipeline's owner-to-owner boundaries (BE-03).

Only a boundary that crosses between owners is exchanged as JSON (decision
BE-01); in-process boundaries stay pydantic objects. For now that is one
boundary: Daniel's analysis -> CM ID.

- ``analysis.schema.json``  what Daniel sends us (same shape as the case model's
                            ``input.employees.schema.json``; Option A).

A schema carries the shape only. The rules between parts (no ``id``, closed
value sets, references) hold through the models and ``ingest_employees``, not
through the schema. Regenerate after every model change with:
``python3 -m pipeline.schema``
"""

import json
from pathlib import Path

from .contracts import Analysis

SCHEMA_DIR = Path(__file__).with_name("schema")

SCHEMAS = {
    "analysis.schema.json": lambda: Analysis.model_json_schema(by_alias=True),
}


def render(name):
    """The text of one schema file, exactly as it is committed."""
    schema = {"$schema": "https://json-schema.org/draft/2020-12/schema",
              "$comment": "Pipeline contract v0.1. Generated by python3 -m pipeline.schema; do not edit.",
              **SCHEMAS[name]()}
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def write_schemas():
    SCHEMA_DIR.mkdir(exist_ok=True)
    for name in SCHEMAS:
        (SCHEMA_DIR / name).write_text(render(name), encoding="utf-8")
    return SCHEMA_DIR


if __name__ == "__main__":
    print(f"wrote {', '.join(SCHEMAS)} to {write_schemas()}")
