"""Ingest for any domain: JSON without IDs in, validated cases out (GD-05, case model v2.1).

The HR ingest (``ingest.py``) reads the shapes of Robin's generator. This one
reads one shape for every domain, in the case model's own names:

    {"cases": [{
        "dossier":       {"folder_title": "...", "description": "..."},
        "facts":         {"policy_number": "HP-2019-0777"},
        "organisations": {"insurer": {"name": "Delta Verzekeringen", "kind": "insurer"}},
        "personas":      {"holder": {"name": "Anna Jansen", "role": "policyholder"},
                          "expert": {"name": "R. de Groot", "role": "inspector",
                                     "organisation": "insurer"}},
        "events":        [{"key": "inspection", "type": "inspection", "date": "2025-03-11",
                           "participants": ["holder", "expert"], "inspector_id": "expert",
                           "signed_by": "expert", "finding": "Leaking pipe."}],
        "documents":     [{"type": "inspection_report", "event": "inspection",
                           "participants": ["holder", "expert"],
                           "metadata": {"confidential": true}}]
    }]}

- **No IDs in the input.** Personas and organisations have a **local key**
  (``holder``, ``insurer``) that events and documents use to point at them; an
  event may have a ``key`` that documents use. Code assigns every ID
  (``P001``, ``ORG-01``, ``EVT-001``, ``DOC-001``) and the case number, made
  with ``number_format`` and checked against the domain's pattern. An ``id``
  anywhere is refused.
- **Events are numbered in date order**, as the HR ingest does.
- **Code fills what the case decides:** a document's ``employee_id`` (the case
  number) and ``document_type``, and its ``document_date`` (its event's date
  when it has one and none is given). Missing case facts are generated by their
  rule (``facts.generate_facts``), with a seed per case.
- **A value written differently from a closed list** (``"water damage"`` for
  ``"Water damage"``) is corrected and recorded; anything else is refused.
- Everything else is checked by the case model of the domain; a refusal names
  the case, the part and the field.
"""

from __future__ import annotations

import datetime as dt
import random
import re
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from .case_model import Case, CaseModel
from .domain import REFERENCE_FORMATS, DomainConfig, get_domain
from .facts import generate_facts
from .format_rules import ID_REGEXES
from .storage import save_case

_KEY = re.compile(r"[a-z][a-z0-9_]{0,39}")


class _NoId(BaseModel):
    @model_validator(mode="before")
    @classmethod
    def _no_id(cls, data):
        if isinstance(data, dict) and "id" in data:
            raise ValueError(
                "IDs are assigned by the case model; remove the id field "
                f"(got id={data['id']!r})."
            )
        return data


class _Strict(_NoId):
    model_config = ConfigDict(extra="forbid")


class DossierIn(_Strict):
    folder_title: str | None = None
    description: str | None = None


class OrganisationIn(_Strict):
    name: str
    kind: str | None = None
    address: str | None = None


class PersonaIn(_Strict):
    name: str
    role: str
    # The local key of the persona's organisation.
    organisation: str | None = None
    salutation: str | None = None
    date_of_birth: dt.date | None = None
    address: str | None = None


class EventIn(_NoId):
    """Common keys; the fields of the event's type come as further keys."""

    model_config = ConfigDict(extra="allow")

    type: str
    date: dt.date
    participants: list[str] = Field(default_factory=list)
    key: str | None = None
    label: str | None = None
    summary: str | None = None
    signed_by: str | None = None


class DocumentIn(_Strict):
    type: str
    event: str | None = None
    participants: list[str] = Field(default_factory=list)
    text: str | None = None
    metadata: dict[str, Any] = Field(default_factory=dict)


class CaseIn(_Strict):
    dossier: DossierIn = Field(default_factory=DossierIn)
    facts: dict[str, Any] = Field(default_factory=dict)
    organisations: dict[str, OrganisationIn] = Field(default_factory=dict)
    personas: dict[str, PersonaIn] = Field(default_factory=dict)
    events: list[EventIn] = Field(default_factory=list)
    documents: list[DocumentIn] = Field(default_factory=list)


class CasesIn(_Strict):
    cases: list[CaseIn] = Field(min_length=1)


class CaseCorrection(BaseModel):
    """A value the case model changed on the way in, shown to the user."""

    case_number: str
    path: str
    message: str


class _Ingest:
    """One case: local keys -> IDs, closed values placed, parts added in order."""

    def __init__(self, domain: DomainConfig, number: str, corrections: list):
        self.domain = domain
        self.number = number
        self.corrections = corrections
        self.keys: dict[str, dict[str, str]] = {"persona": {}, "organisation": {}, "event": {}}

    def closed(self, value, options, path):
        if value is None or value in options:
            return value
        wanted = " ".join(str(value).split()).casefold()
        for option in options:
            if option.casefold() == wanted:
                self.corrections.append(CaseCorrection(
                    case_number=self.number, path=path,
                    message=f"{value!r} written as {option!r}."))
                return option
        raise ValueError(f"{path}: {value!r} is not one of {', '.join(options)}.")

    def key(self, kind, key, path):
        if key is None:
            return None
        if key not in self.keys[kind]:
            raise ValueError(f"{path}: no {kind} with key {key!r} in this case.")
        return self.keys[kind][key]

    def new_key(self, kind, key, path):
        if not _KEY.fullmatch(key) or any(r.fullmatch(key.upper()) for r in ID_REGEXES.values()):
            raise ValueError(f"{path}: key {key!r} must be snake_case and must not look like an ID.")
        if key in self.keys[kind]:
            raise ValueError(f"{path}: key {key!r} is used twice.")


def _build(domain: DomainConfig, number: str, data: CaseIn, rng, corrections) -> Case:
    ing = _Ingest(domain, number, corrections)
    case = CaseModel(number, domain.name)
    case.set_dossier(employee_number=number, folder_title=data.dossier.folder_title or number,
                     description=data.dossier.description)

    given = {name: ing.closed(value, domain.case_facts[name].values, f"facts.{name}")
             if name in domain.case_facts and domain.case_facts[name].values else value
             for name, value in data.facts.items()}
    facts = generate_facts(domain, rng, given)
    if facts is not None:
        case.set_facts(**dict(facts))

    for key, org in data.organisations.items():
        path = f"organisations.{key}"
        ing.new_key("organisation", key, path)
        kind = ing.closed(org.kind, domain.organisation_kinds, f"{path}.kind") \
            if domain.organisation_kinds is not None else org.kind
        ing.keys["organisation"][key] = case.add_organisation(name=org.name, kind=kind,
                                                              address=org.address)

    for key, person in data.personas.items():
        path = f"personas.{key}"
        ing.new_key("persona", key, path)
        ing.keys["persona"][key] = case.add_persona(
            name=person.name, role=ing.closed(person.role, domain.roles, f"{path}.role"),
            organisation_id=ing.key("organisation", person.organisation, f"{path}.organisation"),
            salutation=person.salutation, date_of_birth=person.date_of_birth,
            address=person.address,
        )

    order = sorted(range(len(data.events)), key=lambda i: data.events[i].date)
    for i in order:
        event = data.events[i]
        path = f"events[{i}]"
        spec = domain.event_types.get(event.type)
        if spec is None:
            raise ValueError(f"{path}.type: {event.type!r} is not an event type of "
                             f"{domain.name} ({', '.join(domain.event_types)}).")
        fields = dict(event.model_extra or {})
        for name, value in fields.items():
            field = spec.fields.get(name)
            if field is None:
                continue                      # the case model refuses it, naming the field
            if field.format in REFERENCE_FORMATS:
                fields[name] = ing.key(field.format, value, f"{path}.{name}")
            elif field.values:
                fields[name] = ing.closed(value, field.values, f"{path}.{name}")
        if event.key is not None:
            ing.new_key("event", event.key, f"{path}.key")
        event_id = case.add_event(
            type=event.type, date=event.date, label=event.label, summary=event.summary,
            participant_ids=[ing.key("persona", k, f"{path}.participants") for k in event.participants],
            signed_by=ing.key("persona", event.signed_by, f"{path}.signed_by"),
            **fields,
        )
        if event.key is not None:
            ing.keys["event"][event.key] = event_id

    for i, doc in enumerate(data.documents):
        path = f"documents[{i}]"
        doc_type = ing.closed(doc.type, list(domain.document_types), f"{path}.type")
        event_id = ing.key("event", doc.event, f"{path}.event")
        metadata = {"employee_id": number, "document_type": doc_type, **doc.metadata}
        if "document_date" not in metadata and event_id is not None:
            metadata["document_date"] = case.events[event_id].date
        case.add_document(
            type=doc_type, event_id=event_id, text=doc.text, metadata=metadata,
            participant_ids=[ing.key("persona", k, f"{path}.participants") for k in doc.participants],
        )
    return case.build()


def ingest_cases(domain, data, first_number: int = 1, number_format: str = "{:06d}",
                 seed: int = 0, out_dir=None):
    """Create one case per entry of ``data["cases"]`` in ``domain`` (a name or a
    ``DomainConfig``). Returns ``(cases, corrections)``; with ``out_dir`` the
    cases are saved there, one folder per case, only when every case is valid."""
    domain = get_domain(domain) if isinstance(domain, str) else domain
    batch = CasesIn.model_validate(data)
    cases, corrections = [], []
    for i, case_data in enumerate(batch.cases):
        number = number_format.format(first_number + i)
        if not domain.is_case_number(number):
            raise ValueError(f"case number {number!r} (number_format {number_format!r}) does not "
                             f"match the {domain.name} pattern {domain.case_number_pattern}.")
        try:
            cases.append(_build(domain, number, case_data, random.Random(f"{seed}:{number}"),
                                corrections))
        except (ValidationError, ValueError) as error:
            raise ValueError(f"cases[{i}] ({number}): {error}") from error
    if out_dir is not None:
        for case in cases:
            save_case(case, f"{out_dir}/{case.case_number}")
    return cases, corrections
