"""JSON Schemas for the generator (v1.1, BR-10).

The browser demo cannot run Python, so it builds its TypeScript types from
these files (for example with json-schema-to-typescript):

- ``input.employees.schema.json``   what the generator sends first
- ``input.storylines.schema.json``  what it sends second
- ``case.schema.json``              one case, as the case model writes it

``save_case`` splits a case over four files: ``case.json`` (case_number,
dossier), ``cast.json`` (personas, organisations, employments),
``storyline.json`` (events) and ``documents.json`` (documents); joined, they
are one object of ``case.schema.json``.

A schema carries the shape only. The rules between parts (references, ID
patterns, the order of events) hold only through ``load_case``. Regenerate
after every model change with: python3 -m case_model.schema
"""

import json
from pathlib import Path

from .case_model import Case
from .ingest import EmployeesIn, StorylinesIn

SCHEMA_DIR = Path(__file__).with_name("schema")

SCHEMAS = {
    "input.employees.schema.json": lambda: EmployeesIn.model_json_schema(by_alias=True),
    "input.storylines.schema.json": lambda: StorylinesIn.model_json_schema(by_alias=True),
    # Serialization mode: what the files contain (amounts are strings, "4350.00").
    "case.schema.json": lambda: Case.model_json_schema(mode="serialization"),
}


def render(name):
    """The text of one schema file, exactly as it is committed."""
    schema = {"$schema": "https://json-schema.org/draft/2020-12/schema",
              "$comment": "Case model v1.1. Generated by python3 -m case_model.schema; do not edit.",
              **SCHEMAS[name]()}
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def write_schemas():
    SCHEMA_DIR.mkdir(exist_ok=True)
    for name in SCHEMAS:
        (SCHEMA_DIR / name).write_text(render(name), encoding="utf-8")
    return SCHEMA_DIR


if __name__ == "__main__":
    print(f"wrote {', '.join(SCHEMAS)} to {write_schemas()}")
